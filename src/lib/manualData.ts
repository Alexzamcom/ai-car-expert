function normalize(s: string) {
  return s.toLowerCase().replace(/ё/g, 'е');
}

/** Простой поиск по руководству: заголовок, теги, текст. */
export function searchArticles(query: string, limit = 20): Article[] {
  const q = normalize(query).trim();
  if (!q) return ARTICLES;
  const words = q.split(/[^a-zа-я0-9]+/i).filter((w) => w.length > 2);
  const scored = ARTICLES.map((a) => {
    const title = normalize(a.title);
    const tags = a.tags.map(normalize);
    const text = normalize(a.summary + ' ' + a.body.map((b) => ('p' in b ? b.p : 'list' in b ? b.list.join(' ') : 'warn' in b ? b.warn : b.h)).join(' '));
    let score = 0;
    if (title.includes(q)) score += 10;
    for (const t of tags) if (q.includes(t) || t.includes(q)) score += 6;
    for (const w of words) {
      const stem = w.length > 5 ? w.slice(0, -2) : w;
      if (title.includes(stem)) score += 3;
      if (tags.some((t) => t.includes(stem))) score += 3;
      if (text.includes(stem)) score += 1;
    }
    return { a, score };
  });
  return scored.filter((s) => s.score > 0).sort((x, y) => y.score - x.score).slice(0, limit).map((s) => s.a);
}

export function articleToText(a: Article): string {
  return a.body
    .map((b) => ('p' in b ? b.p : 'list' in b ? b.list.map((l) => `• ${l}`).join('\n') : 'warn' in b ? `⚠ ${b.warn}` : b.h))
    .join('\n');
}
