/* Защита от ложного «управления» автомобилем: такие запросы распознаются и получают честный ответ. */

/** Запросы к системам автомобиля, которые нельзя выполнить без интеграции. */
const VEHICLE_CONTROL_RE =
  /(климат|кондиционер|печк|отоплен|обогрев|подогрев|вентиляц|температур[уы] в салоне|двер|замок|замк|заблокир|разблокир|окн|стекл|багажник|капот|фар|габарит|зеркал|люк|завед[иу]|запуст[иь] двигател|сигнализац|клімат|кондиціонер|двері|вікн|пічк|обігрів|підігрів|фари|дзеркал|багажник)/i;

export function isVehicleControlRequest(text: string) {
  return (
    VEHICLE_CONTROL_RE.test(text) &&
    /(включ|выключ|откр|закр|заблок|разблок|постав|сделай|подними|опусти|запуст|завед|прогре|теплее|холоднее|увімкн|вимкн|відкр|закри|зроби)/i.test(text)
  );
}

