export interface DtcInfo {
  code: string;
  valid: boolean;
  system?: string;
  origin?: string;
  subsystem?: string;
  description?: string;
}

export const DTC_RE = /\b([PCBU])\s?([0-3][0-9A-F]{3})\b/i;

export function decodeDtc(raw: string): DtcInfo {
  const m = raw.toUpperCase().replace(/\s+/g, '').match(/^([PCBU])([0-3])([0-9A-F])([0-9A-F]{2})$/);
  if (!m) return { code: raw.toUpperCase(), valid: false };
  const [, sys, d1, d2, rest] = m;
  const code = `${sys}${d1}${d2}${rest}`;
  let origin: string;
  if (d1 === '0' || d1 === '2') origin = 'Общий код стандарта SAE — одинаков для всех производителей';
  else if (d1 === '1') origin = 'Код производителя — значение зависит от марки автомобиля';
  else origin = sys === 'P' && ['4', '5', '6', '7', '8', '9'].includes(d2) ? 'Общий код стандарта SAE' : 'Код производителя или зарезервирован';
  return {
    code,
    valid: true,
    system: SYSTEMS[sys],
    origin,
    subsystem: sys === 'P' && (d1 === '0' || d1 === '1') ? P_SUBSYSTEMS[d2] : undefined,
    description: KNOWN[code],
  };
}

export function dtcSummary(info: DtcInfo): string {
  if (!info.valid) return `«${info.code}» не похож на код OBD-II. Формат: буква P, C, B или U и четыре символа, например P0420.`;
  return [
    `Код ${info.code}: ${info.description ?? 'нет во встроенном справочнике'}.`,
    `Система: ${info.system}.`,
    info.subsystem ? `Подсистема: ${info.subsystem}.` : '',
    `${info.origin}.`,
  ]
    .filter(Boolean)
    .join(' ');
}
